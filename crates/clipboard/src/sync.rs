/// How often the board is looked at while someone listens: a copy reaches the other Mac within
/// this and a link's delay, and a look at an unchanged board is one cheap call.
pub const POLL: Duration = Duration::from_millis(150);
/// The most bytes of one copy, its files aside, that travel. Text, rich text and pictures are
/// well under it (a Retina screenshot's PNG is a few MiB); a type past what is left of it stays
/// home and the next in the copying app's ranking may still go, so a screenshot's huge TIFF
/// stays while its PNG travels. It bounds what a copy costs the link and memory on both Macs.
pub const SEND_MAX: u64 = 16 << 20;
/// The most a copy's files travel, all together, each a regular file of known size. Most copied
/// files (documents, screenshots, small archives) are under it; bigger copies and folders stay
/// on their Mac.
pub const FILES_MAX: u64 = 16 << 20;
/// How long the other Mac's copy has to arrive in full: past it the board keeps what it had.
/// [`SEND_MAX`] and [`FILES_MAX`] take a few seconds on a slow tailnet path.
pub const FETCH_DEADLINE: Duration = Duration::from_secs(30);

/// What a clipboard does and sends.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub struct ClipboardSettings {
    /// Follow the clipboard at all.
    pub enabled: bool,
    /// Send items marked `org.nspasteboard.AutoGeneratedType` too.
    pub auto_generated: bool,
}

impl Default for ClipboardSettings {
    fn default() -> Self {
        Self {
            enabled: true,
            auto_generated: false,
        }
    }
}

/// The ordering of offers: the newest `(at, origin, seq)` wins. `seq` breaks a tie between two
/// copies of one device in one millisecond.
#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
pub struct Key {
    /// When it was copied, epoch milliseconds, never behind what its origin had seen.
    pub at: i64,
    /// The device it was copied on.
    pub origin: String,
    /// The origin's count of offers.
    pub seq: u64,
}

impl Key {
    /// `offer`'s key.
    #[must_use]
    pub fn of(offer: &ClipboardOffer) -> Self {
        Self {
            at: offer.at,
            origin: offer.origin.clone(),
            seq: offer.seq,
        }
    }
}

/// Epoch milliseconds, for an offer's `at`.
pub trait Clock: Send + Sync + 'static {
    /// Now.
    fn now_ms(&self) -> i64;
}

/// The system's clock.
#[derive(Clone, Copy, Debug, Default)]
pub struct SystemClock;

impl Clock for SystemClock {
    fn now_ms(&self) -> i64 {
        SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map_or(0, |since| {
                i64::try_from(since.as_millis()).unwrap_or(i64::MAX)
            })
    }
}

/// The Macs whose offers this one applies, as their copies' bytes and files are fetched.
#[async_trait]
pub trait Peers: Send + Sync + 'static {
    /// The bytes of type `uti` of item `item` of `origin`'s offer `seq`.
    ///
    /// # Errors
    ///
    /// The origin is gone, or no longer holds the offer.
    async fn fetch(
        &self,
        origin: &str,
        seq: u64,
        item: usize,
        uti: &str,
    ) -> Result<Vec<u8>, String>;

    /// The file item `item` of `origin`'s offer `seq` names, copied into the local
    /// folder `into` under its own name; returns its local path once all of it is there.
    ///
    /// # Errors
    ///
    /// The origin is gone, no longer holds the offer, or the copy failed.
    async fn fetch_file(
        &self,
        origin: &str,
        seq: u64,
        item: usize,
        into: &std::path::Path,
    ) -> Result<PathBuf, String>;
}

/// Reads [`PasteAccess`] for the board, cheaply enough to ask on every look.
pub type Access = Arc<dyn Fn() -> PasteAccess + Send + Sync>;

/// What a [`Clipboard`] works with.
pub struct Config {
    /// This Mac's device id.
    pub device: String,
    /// The pasteboard.
    pub board: Arc<dyn Board>,
    /// The Macs it fetches from.
    pub peers: Arc<dyn Peers>,
    /// Stamps offers.
    pub clock: Arc<dyn Clock>,
    /// Whether the board may be read without a prompt.
    pub access: Access,
    /// Where received files land, one folder per offer: `~/Library/Caches/<bundle>/clipboard`.
    pub cache: PathBuf,
    /// The settings it starts with.
    pub settings: ClipboardSettings,
}

/// What became of the other Mac's offer.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Received {
    /// It is on the board.
    Applied,
    /// Its bytes or files are on their way: it is written once they land, unless something newer
    /// came meanwhile.
    Fetching,
    /// Something newer was applied or announced here.
    Stale,
    /// Not taken: sync is off, it is this device's own, another device is followed, or it holds
    /// nothing.
    Ignored,
    /// The board refused the write.
    Failed,
}

/// One Mac's clipboard. Cheap to clone.
#[derive(Clone)]
pub struct Clipboard(Arc<Inner>);

struct Inner {
    device: String,
    board: Arc<dyn Board>,
    peers: Arc<dyn Peers>,
    clock: Arc<dyn Clock>,
    access: Access,
    cache: PathBuf,
    runtime: Handle,
    state: Mutex<State>,
    /// The newest offer announced here.
    offers: watch::Sender<Option<Arc<ClipboardOffer>>>,
    /// The device whose session has focus.
    follow: watch::Sender<Option<String>>,
    settings: watch::Sender<ClipboardSettings>,
    /// How many subscriptions are open.
    listeners: watch::Sender<usize>,
    /// Whether this Mac's newest copy stays here past the caps.
    withheld: watch::Sender<Option<Withheld>>,
}

#[derive(Default)]
struct State {
    /// The count last looked at.
    seen: Option<isize>,
    /// The count this Mac's own last write left.
    own: Option<isize>,
    /// The last offer's sequence number.
    seq: u64,
    /// The newest offer applied or announced.
    newest: Option<Key>,
    /// The newest announced offer's bytes, while the board still holds it.
    announced: Option<Announced>,
}

/// An announced offer's bytes, read when it was copied.
struct Announced {
    seq: u64,
    /// Per offer item: each type offered and its bytes.
    items: Vec<Vec<(String, Bytes)>>,
}

impl Clipboard {
    /// A clipboard over `config`, its fetches run on `runtime`.
    #[must_use]
    pub fn new(config: Config, runtime: Handle) -> Self {
        // Sequence numbers start at the clock, so they keep rising across restarts.
        let seq = u64::try_from(config.clock.now_ms()).unwrap_or(0);
        Self(Arc::new(Inner {
            device: config.device,
            board: config.board,
            peers: config.peers,
            clock: config.clock,
            access: config.access,
            cache: config.cache,
            runtime,
            state: Mutex::new(State {
                seq,
                ..State::default()
            }),
            offers: watch::Sender::new(None),
            follow: watch::Sender::new(None),
            settings: watch::Sender::new(config.settings),
            listeners: watch::Sender::new(0),
            withheld: watch::Sender::new(None),
        }))
    }

    /// This Mac's device id.
    #[must_use]
    pub fn device(&self) -> &str {
        &self.0.device
    }

    /// The settings now.
    #[must_use]
    pub fn settings(&self) -> ClipboardSettings {
        *self.0.settings.borrow()
    }

    /// Changes the settings.
    pub fn set_settings(&self, settings: ClipboardSettings) {
        self.0.settings.send_replace(settings);
    }

    /// Whether the board may be read without a prompt, as the access check says now.
    #[must_use]
    pub fn access(&self) -> PasteAccess {
        (self.0.access)()
    }

    /// While `device`'s session has focus, only its offers apply here and this Mac's go only to
    /// it; `None` follows nobody, and nothing applies or goes.
    pub fn follow(&self, device: Option<String>) {
        self.0.follow.send_if_modified(|followed| {
            let changed = *followed != device;
            *followed = device;
            changed
        });
    }

    /// Stops following `device`, if it is the one followed: a window losing focus after another
    /// gained it leaves the newer one followed.
    pub fn unfollow(&self, device: &str) {
        self.0.follow.send_if_modified(|followed| {
            let ours = followed.as_deref() == Some(device);
            if ours {
                *followed = None;
            }
            ours
        });
    }

    /// The device followed, if any.
    #[must_use]
    pub fn followed(&self) -> Option<String> {
        self.0.follow.borrow().clone()
    }

    /// The newest offer applied or announced here.
    #[must_use]
    pub fn newest(&self) -> Option<Key> {
        self.0.state.lock().newest.clone()
    }

    /// The newest offer announced here.
    #[must_use]
    pub fn announced(&self) -> Option<Arc<ClipboardOffer>> {
        self.0.offers.borrow().clone()
    }

    /// Whether this Mac's newest copy stays here, whole or in part, for being past the caps or
    /// naming a folder: set when a look reads such a copy, `None` once a newer copy here is within
    /// them or the other Mac's copy is written here. Each change wakes the receiver.
    #[must_use]
    pub fn withheld(&self) -> watch::Receiver<Option<Withheld>> {
        self.0.withheld.subscribe()
    }

    /// Says whether the newest copy here stays here.
    fn set_withheld(&self, withheld: Option<Withheld>) {
        self.0.withheld.send_if_modified(|held| {
            let changed = *held != withheld;
            *held = withheld;
            changed
        });
    }

    /// This Mac's offers, as `subscriber` (the other Mac's device id; `None` for a reader of
    /// this Mac's own) may see them: the newest at once, then each new one. While another device
    /// is followed, a subscriber that is not it sees nothing. The board is watched while any
    /// subscription is open.
    pub fn subscribe(&self, subscriber: Option<String>) -> BoxStream<'static, ClipboardOffer> {
        let start = Subscription {
            offers: self.0.offers.subscribe(),
            follow: self.0.follow.subscribe(),
            subscriber,
            sent: None,
            _listening: Listening::new(&self.0),
        };
        Box::pin(futures::stream::unfold(start, |mut sub| async move {
            let offer = sub.next().await?;
            Some((offer, sub))
        }))
    }

    /// Watches the board every [`POLL`] while sync is on and someone listens, until the
    /// clipboard is dropped. Each look runs on a blocking thread: a board's calls may wait on
    /// the pasteboard server.
    pub fn watcher(&self) -> impl Future<Output = ()> + Send + 'static {
        let weak = Arc::downgrade(&self.0);
        let mut listeners = self.0.listeners.subscribe();
        let mut settings = self.0.settings.subscribe();
        async move {
            let mut tick = tokio::time::interval(POLL);
            tick.set_missed_tick_behavior(MissedTickBehavior::Delay);
            loop {
                loop {
                    let idle = *listeners.borrow_and_update() == 0
                        || !settings.borrow_and_update().enabled;
                    if !idle {
                        break;
                    }
                    let woke = tokio::select! {
                        changed = listeners.changed() => changed,
                        changed = settings.changed() => changed,
                    };
                    if woke.is_err() {
                        return;
                    }
                    // The first look is at once: focus came, and a copy made meanwhile goes now.
                    tick.reset_immediately();
                }
                tick.tick().await;
                let Some(inner) = weak.upgrade() else { return };
                let clipboard = Self(inner);
                if tokio::task::spawn_blocking(move || clipboard.look())
                    .await
                    .is_err()
                {
                    return;
                }
            }
        }
    }

    /// Looks at the board once: a new offer when it changed by someone else's copy and holds
    /// something that may leave, announced to every subscription.
    pub fn look(&self) -> Option<Arc<ClipboardOffer>> {
        let inner = &*self.0;
        let settings = self.settings();
        // Where a read would prompt or fail, copies stay here; the first look once it may read
        // sends the copy standing then.
        if !settings.enabled || !(inner.access)().reads_freely() {
            return None;
        }
        let count = inner.board.change_count();
        {
            let mut state = inner.state.lock();
            if state.seen == Some(count) {
                return None;
            }
            state.seen = Some(count);
            // What was announced is not the board's any more.
            state.announced = None;
            if state.own == Some(count) {
                return None;
            }
        }
        let read = read_board(&*inner.board, settings);
        let mut state = inner.state.lock();
        // The board moved while it was read (the other Mac's offer landed, or another copy): the
        // next look reads it again, unless it was this Mac's own write.
        if inner.board.change_count() != count {
            state.seen = None;
            return None;
        }
        // A private copy stays home on purpose: it is no copy past the caps.
        let withheld = read.as_ref().and_then(|read| read.withheld);
        if let Some(size) = withheld {
            tracing::debug!(?size, "a copy past the clipboard's caps stays home");
        }
        self.set_withheld(withheld.map(|size| Withheld {
            at: inner.clock.now_ms(),
            size,
        }));
        let read = read.filter(|read| !read.items.is_empty())?;
        state.seq = state.seq.saturating_add(1);
        let floor = state
            .newest
            .as_ref()
            .map_or(i64::MIN, |newest| newest.at.saturating_add(1));
        let offer = Arc::new(ClipboardOffer {
            origin: inner.device.clone(),
            seq: state.seq,
            at: inner.clock.now_ms().max(floor),
            items: read.items,
        });
        state.newest = Some(Key::of(&offer));
        state.announced = Some(Announced {
            seq: state.seq,
            items: read.held,
        });
        drop(state);
        inner.offers.send_replace(Some(Arc::clone(&offer)));
        tracing::debug!(
            seq = offer.seq,
            items = offer.items.len(),
            "clipboard announced"
        );
        Some(offer)
    }

    /// Takes the other Mac's offer when it is newer than everything applied or announced here
    /// and the followed device made it: written at once when it rode inline whole, else once
    /// the rest of it is fetched.
    pub fn receive(&self, offer: ClipboardOffer) -> Received {
        let inner = &*self.0;
        if !self.settings().enabled || offer.origin == inner.device || offer.items.is_empty() {
            return Received::Ignored;
        }
        if inner.follow.borrow().as_deref() != Some(offer.origin.as_str()) {
            return Received::Ignored;
        }
        let plan = Plan::of(&offer);
        if plan.items.is_empty() {
            return Received::Ignored;
        }
        let key = Key::of(&offer);
        {
            let mut state = inner.state.lock();
            if state.newest.as_ref().is_some_and(|newest| key <= *newest) {
                return Received::Stale;
            }
            state.newest = Some(key.clone());
            state.announced = None;
        }
        let dir = inner.cache.join(format!("{}-{}", offer.origin, offer.seq));
        if plan.whole() {
            return self.land(&key, &plan.written(&offer.origin), dir);
        }
        let clipboard = Arc::downgrade(&self.0);
        let peers = Arc::clone(&inner.peers);
        let _task = inner.runtime.spawn(async move {
            let mut plan = plan;
            let fetched =
                tokio::time::timeout(FETCH_DEADLINE, gather(&*peers, &offer, &mut plan, &dir))
                    .await
                    .unwrap_or_else(|_late| Err("past the deadline".to_owned()));
            if let Err(error) = fetched {
                tracing::debug!(origin = %offer.origin, seq = offer.seq, %error, "a clipboard copy did not arrive");
                return;
            }
            let Some(inner) = clipboard.upgrade() else {
                return;
            };
            let clipboard = Self(inner);
            let items = plan.written(&offer.origin);
            // Writing may wait on the pasteboard server: off the runtime's threads.
            let _landed =
                tokio::task::spawn_blocking(move || clipboard.land(&key, &items, dir)).await;
        });
        Received::Fetching
    }

    /// Writes the other Mac's copy `key`, all of it here, unless something newer was applied or
    /// announced meanwhile; its files are in `dir`, the one cache folder kept.
    fn land(&self, key: &Key, items: &[Item], dir: PathBuf) -> Received {
        let inner = &*self.0;
        let mut state = inner.state.lock();
        if state.newest.as_ref() != Some(key) {
            return Received::Stale;
        }
        // Written under the state lock, so a look in between cannot take it for a copy.
        let Some(count) = inner.board.write(items) else {
            return Received::Failed;
        };
        state.own = Some(count);
        state.seen = Some(count);
        drop(state);
        // The newest copy here is the other Mac's now.
        self.set_withheld(None);
        tracing::debug!(origin = %key.origin, seq = key.seq, "clipboard applied");
        self.keep_only(dir);
        Received::Applied
    }

    /// The bytes of type `uti` of item `item` of this Mac's offer `seq`, for the other Mac;
    /// `None` when the offer is not the newest announced, the board moved on, or it did not
    /// offer that.
    #[must_use]
    pub fn serve(&self, seq: u64, item: usize, uti: &str) -> Option<Bytes> {
        self.0
            .state
            .lock()
            .announced
            .as_ref()
            .filter(|announced| announced.seq == seq)?
            .items
            .get(item)?
            .iter()
            .find(|(kind, _)| kind == uti)
            .map(|(_, bytes)| bytes.clone())
    }

    /// The local path of the file item `item` of this Mac's offer `seq` names, for the other Mac;
    /// `None` as for [`Self::serve`], or when the item names no file.
    #[must_use]
    pub fn serve_file(&self, seq: u64, item: usize) -> Option<PathBuf> {
        path_of_url(&self.serve(seq, item, FILE_URL_TYPE)?)
    }

    /// Empties the file cache but for `keep`: no history is kept.
    fn keep_only(&self, keep: PathBuf) {
        let cache = self.0.cache.clone();
        let _task = self.0.runtime.spawn_blocking(move || {
            let Ok(entries) = std::fs::read_dir(&cache) else {
                return;
            };
            for entry in entries.flatten() {
                let path = entry.path();
                if path != keep
                    && let Err(error) = std::fs::remove_dir_all(&path)
                {
                    tracing::debug!(path = %path.display(), %error, "clipboard cache entry kept");
                }
            }
        });
    }
}

/// Counts the open subscriptions while it lives.
struct Listening(Weak<Inner>);

impl Listening {
    fn new(inner: &Arc<Inner>) -> Self {
        inner.listeners.send_modify(|n| *n = n.saturating_add(1));
        Self(Arc::downgrade(inner))
    }
}

impl Drop for Listening {
    fn drop(&mut self) {
        if let Some(inner) = self.0.upgrade() {
            inner.listeners.send_modify(|n| *n = n.saturating_sub(1));
        }
    }
}

struct Subscription {
    offers: watch::Receiver<Option<Arc<ClipboardOffer>>>,
    follow: watch::Receiver<Option<String>>,
    subscriber: Option<String>,
    sent: Option<Key>,
    _listening: Listening,
}

impl Subscription {
    async fn next(&mut self) -> Option<ClipboardOffer> {
        loop {
            let offer = self.offers.borrow_and_update().clone();
            let followed = self.follow.borrow_and_update().clone();
            if let Some(offer) = offer
                && visible(followed.as_deref(), self.subscriber.as_deref())
            {
                let key = Key::of(&offer);
                if self.sent.as_ref() != Some(&key) {
                    self.sent = Some(key);
                    return Some((*offer).clone());
                }
            }
            tokio::select! {
                changed = self.offers.changed() => changed.ok()?,
                changed = self.follow.changed() => changed.ok()?,
            }
        }
    }
}

/// Whether `subscriber` sees this Mac's offers while `followed` is followed: the followed device
/// alone, and a reader of this Mac's own always.
fn visible(followed: Option<&str>, subscriber: Option<&str>) -> bool {
    match (followed, subscriber) {
        (_, None) => true,
        (None, Some(_)) => false,
        (Some(followed), Some(subscriber)) => followed == subscriber,
    }
}

/// An offer's items as read off the board.
#[derive(Default)]
struct Read {
    items: Vec<ClipboardItem>,
    /// Per offer item: each type offered and its bytes.
    held: Vec<Vec<(String, Bytes)>>,
    /// An item stays home past the caps: the size of what stays, `None` for a folder.
    withheld: Option<Option<u64>>,
}

/// What may leave of the board's contents, read now, and what stays past the caps; `None` when
/// a privacy marker keeps it all home.
///
/// A privacy marker keeps the whole copy home, whichever item it sits on: a password manager
/// may write it as an item of its own. Items that name files leave only when the files do
/// ([`files_kept`]), and each type only while the copy is within [`SEND_MAX`]; an item none of
/// whose types is within it stays home, and says so.
fn read_board(board: &dyn Board, settings: ClipboardSettings) -> Option<Read> {
    let all = board.items();
    let marked = |kind: &str| all.iter().flatten().any(|t| t == kind);
    if marked(ORIGIN_TYPE)
        || marked(REMOTE_CLIPBOARD_TYPE)
        || marked(CONCEALED_TYPE)
        || marked(TRANSIENT_TYPE)
        || (!settings.auto_generated && marked(AUTO_GENERATED_TYPE))
    {
        return None;
    }
    let kept_files = files_kept(board, &all);
    let mut left = SEND_MAX;
    let mut read = Read {
        withheld: kept_files,
        ..Read::default()
    };
    for (n, kinds) in all.iter().enumerate() {
        if kept_files.is_some() && kinds.iter().any(|t| t == FILE_URL_TYPE) {
            continue;
        }
        let mut types = Vec::new();
        let mut held: Vec<(String, Bytes)> = Vec::new();
        let mut too_big: Option<u64> = None;
        for uti in kinds.iter().filter(|t| carried(t)) {
            if held.iter().any(|(t, _)| t == uti) {
                continue;
            }
            let bytes = match board.data_within(n, uti, left) {
                Some(Capped::Data(bytes)) => bytes,
                Some(Capped::TooBig(size)) => {
                    tracing::debug!(uti, size, "a type past the clipboard's cap stays home");
                    too_big = Some(too_big.map_or(size, |seen| seen.max(size)));
                    continue;
                }
                None => continue,
            };
            let size = u64::try_from(bytes.len()).unwrap_or(u64::MAX);
            left = left.saturating_sub(size);
            types.push(ClipboardType {
                uti: uti.clone(),
                size,
                inline: (size <= INLINE_MAX).then(|| Inline(bytes.clone())),
                file_size: if uti == FILE_URL_TYPE {
                    file_size(&bytes)
                } else {
                    None
                },
            });
            held.push((uti.clone(), Bytes::from(bytes)));
        }
        if !types.is_empty() {
            read.items.push(ClipboardItem { types });
            read.held.push(held);
        } else if let Some(size) = too_big {
            // Nothing of this item is within the cap: it stays home.
            let stays = read.withheld.flatten().map_or(size, |seen| seen.max(size));
            read.withheld = Some(Some(stays));
        }
    }
    Some(read)
}

/// Whether the files the copy on `board` names stay home: `None` when they travel (each a
/// regular file, together no more than [`FILES_MAX`], or none named), else their size together,
/// `None` within for a folder, whose size needs a walk, so a copy with one stays home.
fn files_kept(board: &dyn Board, all: &[Vec<String>]) -> Option<Option<u64>> {
    let mut total = 0_u64;
    for (n, kinds) in all.iter().enumerate() {
        if !kinds.iter().any(|t| t == FILE_URL_TYPE) {
            continue;
        }
        let Some(size) = board.data(n, FILE_URL_TYPE).and_then(|url| file_size(&url)) else {
            return Some(None);
        };
        total = total.saturating_add(size);
    }
    (total > FILES_MAX).then_some(Some(total))
}

/// Whether the files `offer` names may be fetched: each a regular file of known size, together
/// no more than [`FILES_MAX`]; true of an offer of none.
fn files_fit(offer: &ClipboardOffer) -> bool {
    let mut total = 0_u64;
    for kind in offer
        .items
        .iter()
        .flat_map(|item| &item.types)
        .filter(|t| t.uti == FILE_URL_TYPE)
    {
        let Some(size) = kind.file_size else {
            return false;
        };
        total = total.saturating_add(size);
    }
    total <= FILES_MAX
}

/// One type of the other Mac's offer, as it is written here.
enum Rep {
    /// Its bytes, here.
    Here(Vec<u8>),
    /// Its bytes, to fetch from the origin.
    Fetch,
    /// The file it names, to fetch into the cache: written as the local copy's URL.
    File,
}

/// The other Mac's offer as it is written here.
struct Plan {
    /// Per item written: its place in the offer and its types, in the origin's order.
    items: Vec<(usize, Vec<(String, Rep)>)>,
}

impl Plan {
    fn of(offer: &ClipboardOffer) -> Self {
        let files = files_fit(offer);
        let mut items = Vec::with_capacity(offer.items.len());
        for (n, item) in offer.items.iter().enumerate() {
            if !files && item.types.iter().any(|t| t.uti == FILE_URL_TYPE) {
                continue;
            }
            let mut reps: Vec<(String, Rep)> = Vec::new();
            // The other Mac cannot plant a marker: only types that travel are written.
            for kind in item.types.iter().filter(|t| carried(&t.uti)) {
                if reps.iter().any(|(t, _)| *t == kind.uti) {
                    continue;
                }
                let rep = if kind.uti == FILE_URL_TYPE {
                    // The origin's path means nothing here: the file comes into the cache.
                    Rep::File
                } else if let Some(Inline(bytes)) = &kind.inline {
                    Rep::Here(bytes.clone())
                } else {
                    Rep::Fetch
                };
                reps.push((kind.uti.clone(), rep));
            }
            if !reps.is_empty() {
                items.push((n, reps));
            }
        }
        Self { items }
    }

    /// Whether every type is here.
    fn whole(&self) -> bool {
        self.items
            .iter()
            .flat_map(|(_, reps)| reps)
            .all(|(_, rep)| matches!(rep, Rep::Here(_)))
    }

    /// The items to write, `origin`'s marker on each; a type not here is left out.
    fn written(self, origin: &str) -> Vec<Item> {
        self.items
            .into_iter()
            .map(|(_, reps)| {
                let mut data = vec![(ORIGIN_TYPE.to_owned(), origin.as_bytes().to_vec())];
                data.extend(reps.into_iter().filter_map(|(uti, rep)| match rep {
                    Rep::Here(bytes) => Some((uti, bytes)),
                    Rep::Fetch | Rep::File => None,
                }));
                Item::data(data)
            })
            .collect()
    }
}

/// Fetches from `offer`'s origin every type and file of `plan` not here yet, files into `dir`.
///
/// # Errors
///
/// The origin is gone or has moved on, a file did not land, or the bytes went past
/// [`SEND_MAX`].
async fn gather(
    peers: &dyn Peers,
    offer: &ClipboardOffer,
    plan: &mut Plan,
    dir: &Path,
) -> Result<(), String> {
    let named: Vec<usize> = plan
        .items
        .iter()
        .filter(|(_, reps)| reps.iter().any(|(_, rep)| matches!(rep, Rep::File)))
        .map(|(n, _)| *n)
        .collect();
    let mut urls = if named.is_empty() {
        Vec::new()
    } else {
        files::fetch(peers, &offer.origin, offer.seq, dir, &named).await?
    };
    let mut fetched = 0_u64;
    for (n, reps) in &mut plan.items {
        for (uti, rep) in reps.iter_mut() {
            match rep {
                Rep::Here(_) => {}
                Rep::Fetch => {
                    let bytes = peers
                        .fetch(&offer.origin, offer.seq, *n, uti.as_str())
                        .await?;
                    let size = u64::try_from(bytes.len()).unwrap_or(u64::MAX);
                    fetched = fetched.saturating_add(size);
                    if fetched > SEND_MAX {
                        return Err("the copy is past the cap".to_owned());
                    }
                    *rep = Rep::Here(bytes);
                }
                Rep::File => {
                    let at = urls
                        .iter()
                        .position(|(item, _)| *item == *n)
                        .ok_or_else(|| "a file did not land".to_owned())?;
                    *rep = Rep::Here(urls.swap_remove(at).1);
                }
            }
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_order_by_time_then_origin_then_seq() {
        let key = |at, origin: &str, seq| Key {
            at,
            origin: origin.to_owned(),
            seq,
        };
        assert!(key(2, "a", 1) > key(1, "z", 9));
        assert!(key(1, "b", 1) > key(1, "a", 9));
        assert!(key(1, "a", 2) > key(1, "a", 1));
    }

    #[test]
    fn only_the_followed_session_sees_and_this_mac_always() {
        assert!(!visible(None, Some("b")), "nobody followed: nothing goes");
        assert!(visible(Some("b"), Some("b")));
        assert!(!visible(Some("b"), Some("c")));
        assert!(visible(Some("b"), None));
        assert!(visible(None, None));
    }

    #[test]
    fn small_regular_files_travel_and_folders_stay() {
        let offer = |sizes: &[Option<u64>]| ClipboardOffer {
            origin: "a".into(),
            seq: 1,
            at: 1,
            items: sizes
                .iter()
                .map(|&file_size| ClipboardItem {
                    types: vec![ClipboardType {
                        uti: FILE_URL_TYPE.into(),
                        size: 20,
                        inline: None,
                        file_size,
                    }],
                })
                .collect(),
        };
        assert!(files_fit(&offer(&[Some(1 << 20), Some(2 << 20)])));
        assert!(files_fit(&offer(&[Some(FILES_MAX)])));
        assert!(!files_fit(&offer(&[Some(FILES_MAX), Some(1)])));
        assert!(!files_fit(&offer(&[Some(1), None])), "a folder");
        assert!(files_fit(&offer(&[])), "no files: nothing held back");
        assert!(Plan::of(&offer(&[Some(1), None])).items.is_empty());
    }
}
