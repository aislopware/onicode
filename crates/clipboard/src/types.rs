//! Pasteboard types: the markers that keep a copy home, which types travel, and the formats
//! every end knows by name.
//!
//! Ported from slopty's `slopty-proto` `transfer.rs` (MIT, same authors), by way of
//! `onicode-desktop-proto`.

/// The private pasteboard type every onicode write carries, holding the origin device's id: a
/// watcher that finds it knows the change came from onicode and does not announce it back.
pub const ORIGIN_TYPE: &str = "com.aislopware.onicode.origin";

/// nspasteboard.org's marker for a secret, such as a password manager's copy: never sent.
pub const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";

/// nspasteboard.org's marker for contents that are about to go again: never sent.
pub const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";

/// nspasteboard.org's marker for contents an app put there on its own, not the person's copy:
/// sent only when the owner opts in.
pub const AUTO_GENERATED_TYPE: &str = "org.nspasteboard.AutoGeneratedType";

/// Apple's marker for a copy that came from another device by Universal Clipboard: never sent
/// again, as that device sends it itself.
pub const REMOTE_CLIPBOARD_TYPE: &str = "com.apple.is-remote-clipboard";

/// A file on the pasteboard, as its `file://` URL.
pub const FILE_URL_TYPE: &str = "public.file-url";

/// Whether a type on an Apple pasteboard travels in an offer.
///
/// Left behind: dynamic types (`dyn.…`), which name nothing on another machine; the
/// pre-UTI names AppKit still lists beside their UTIs (`NSStringPboardType`, `Apple PNG
/// pasteboard type`, `CorePasteboardFlavorType 0x…`), whose bytes the UTI already carries;
/// file promises, which only the copying process can keep; and the markers.
#[must_use]
pub fn carried(board_type: &str) -> bool {
    let legacy = !board_type.contains('.') || board_type.contains(' ');
    let marker = board_type == ORIGIN_TYPE
        || board_type == REMOTE_CLIPBOARD_TYPE
        || board_type.starts_with("org.nspasteboard.");
    let promise = board_type.starts_with("com.apple.pasteboard.promised-")
        || board_type == "com.apple.NSFilePromiseItemMetaData";
    !(legacy || marker || promise || board_type.starts_with("dyn."))
}

/// A representation every end knows by name, whatever its platform calls it.
///
/// Each end maps it to its own pasteboard's types at its board (an Apple UTI on a Mac or an
/// iPhone, a MIME type elsewhere): [`board_type`].
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum ClipFormat {
    /// A file, as its `file://` URL: one per item (`text/uri-list`).
    FileUrls,
    /// `image/png`.
    Png,
    /// `image/tiff`, what a Mac screenshot is on its pasteboard.
    Tiff,
    /// `text/rtf`.
    Rtf,
    /// `text/html`.
    Html,
    /// `text/plain`, UTF-8.
    Text,
}

impl ClipFormat {
    /// Every format, richest first.
    pub const ALL: [Self; 6] = [
        Self::FileUrls,
        Self::Png,
        Self::Tiff,
        Self::Rtf,
        Self::Html,
        Self::Text,
    ];

    /// The MIME type.
    #[must_use]
    pub const fn mime(self) -> &'static str {
        match self {
            Self::FileUrls => "text/uri-list",
            Self::Png => "image/png",
            Self::Tiff => "image/tiff",
            Self::Rtf => "text/rtf",
            Self::Html => "text/html",
            Self::Text => "text/plain;charset=utf-8",
        }
    }

    /// The Apple UTI.
    #[must_use]
    pub const fn uti(self) -> &'static str {
        match self {
            Self::FileUrls => FILE_URL_TYPE,
            Self::Png => "public.png",
            Self::Tiff => "public.tiff",
            Self::Rtf => "public.rtf",
            Self::Html => "public.html",
            Self::Text => "public.utf8-plain-text",
        }
    }
}

/// The type `format` has on this platform's pasteboard: its UTI on Apple's, else its MIME type.
#[must_use]
pub const fn board_type(format: ClipFormat) -> &'static str {
    if cfg!(target_os = "macos") {
        format.uti()
    } else {
        format.mime()
    }
}

/// The format a pasteboard type is, if it is one.
#[must_use]
pub fn format_of(board_type: &str) -> Option<ClipFormat> {
    ClipFormat::ALL
        .into_iter()
        .find(|&format| self::board_type(format) == board_type)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every Apple type travels but dynamic ones, the pre-UTI names, file promises and the
    /// markers.
    #[test]
    fn only_types_that_mean_something_elsewhere_travel() {
        for kept in [
            "public.png",
            "public.utf8-plain-text",
            "public.rtf",
            "public.html",
            "public.tiff",
            "com.apple.webarchive",
            "com.adobe.pdf",
            FILE_URL_TYPE,
        ] {
            assert!(carried(kept), "{kept}");
        }
        for left in [
            "dyn.ah62d4rv4gu8y",
            "NSStringPboardType",
            "Apple PNG pasteboard type",
            "CorePasteboardFlavorType 0x75726C20",
            "com.apple.pasteboard.promised-file-url",
            ORIGIN_TYPE,
            CONCEALED_TYPE,
            TRANSIENT_TYPE,
            AUTO_GENERATED_TYPE,
            REMOTE_CLIPBOARD_TYPE,
            "org.nspasteboard.source",
        ] {
            assert!(!carried(left), "{left}");
        }
    }

    /// Each format is its own type on this board and back; anything else is no format.
    #[test]
    fn each_format_is_a_board_type_and_back() {
        for format in ClipFormat::ALL {
            assert_eq!(format_of(board_type(format)), Some(format));
            assert!(!format.mime().is_empty());
        }
        assert_eq!(format_of("com.adobe.pdf"), None);
        assert_eq!(format_of(ORIGIN_TYPE), None);
    }
}
