//! Settings → General → Clipboard: whether the clipboard follows the owner between their
//! devices, whether apps' own copies go too, and the "Paste from Other Apps" permission this Mac
//! needs to read the clipboard while the owner is at another one.
//!
//! The settings live in each engine (`ClipboardSettings`); a change is sent to every engine this
//! app knows, and this device's reply is what the card shows.

use gpui::prelude::*;
use gpui::{App, Context, Entity, Subscription, Task, div, px};
use onicode_engine::clipboard::{CLIPBOARD_FOLLOW, FollowParams, PasteAccess, SettingsReply};
use onicode_rpc::methods;

use crate::popover::Loadable;
use crate::settings::search::{SearchAnchor, SettingId};
use crate::settings::widgets;
use crate::state::AppState;
use crate::theme::Theme;

/// The remote desktop viewer of `device_id` gained (`focused`) or lost focus: while one has it,
/// the clipboard follows that session both ways. Fire and forget; nothing to show if it fails.
pub fn follow(state: Option<&Entity<AppState>>, device_id: &str, focused: bool, cx: &mut App) {
    let Some(engine) = state.and_then(|state| state.read(cx).engine().cloned()) else {
        return;
    };
    let params = serde_json::to_value(FollowParams {
        device_id: device_id.to_owned(),
        focused,
    })
    .unwrap_or_default();
    cx.spawn(async move |_cx| {
        if let Err(error) = engine.client().call(CLIPBOARD_FOLLOW, params).await {
            tracing::debug!(%error, "the engine did not hear the viewer's focus");
        }
    })
    .detach();
}

pub struct ClipboardCard {
    state: Entity<AppState>,
    settings: Loadable<SettingsReply>,
    error: Option<String>,
    task: Option<Task<()>>,
    _state: Subscription,
}

/// A change the person made.
#[derive(Clone, Copy)]
enum Change {
    Enabled(bool),
    AutoGenerated(bool),
}

impl ClipboardCard {
    pub fn new(state: Entity<AppState>, cx: &mut Context<Self>) -> Self {
        // Settings can open before the engine connects: load once it does.
        let state_sub = cx.observe(&state, |this: &mut Self, _, cx| {
            if matches!(this.settings, Loadable::Idle) {
                this.call(None, cx);
            }
        });
        let mut card = Self {
            state,
            settings: Loadable::Idle,
            error: None,
            task: None,
            _state: state_sub,
        };
        card.call(None, cx);
        card
    }

    /// Reads this device's settings, or sets `change` on every engine this app knows and reads
    /// back this device's.
    fn call(&mut self, change: Option<Change>, cx: &mut Context<Self>) {
        let state = self.state.read(cx);
        let Some(engine) = state.engine().cloned() else {
            return;
        };
        let params = match change {
            None => serde_json::json!({}),
            Some(Change::Enabled(on)) => serde_json::json!({ "enabled": on }),
            Some(Change::AutoGenerated(on)) => serde_json::json!({ "autoGenerated": on }),
        };
        // The other engines this app knows, each set on its own; a phone keeps no clipboard
        // settings, and one that is offline catches up when the person flips the switch again.
        let others: Vec<String> = if change.is_some() {
            state
                .devices
                .iter()
                .filter(|device| {
                    state.local_device_id.as_deref() != Some(device.id.as_str())
                        && matches!(device.platform.as_str(), "macos" | "linux")
                })
                .map(|device| device.id.clone())
                .collect()
        } else {
            Vec::new()
        };
        if matches!(self.settings, Loadable::Idle) {
            self.settings = Loadable::Loading;
        }
        self.task = Some(cx.spawn(async move |this, cx| {
            let client = engine.client();
            for device in others {
                let mut params = params.clone();
                if let Some(map) = params.as_object_mut() {
                    map.insert("targetDeviceId".to_owned(), device.clone().into());
                }
                if let Err(error) = client.call(methods::CLIPBOARD_SETTINGS, params).await {
                    tracing::debug!(%device, %error, "clipboard settings not set there");
                }
            }
            let result = client
                .call(methods::CLIPBOARD_SETTINGS, params)
                .await
                .map_err(|e| e.to_string())
                .and_then(|v| {
                    serde_json::from_value::<SettingsReply>(v).map_err(|e| e.to_string())
                });
            let _gone = this.update(cx, |card, cx| {
                match result {
                    Ok(settings) => {
                        card.settings = Loadable::Ready(settings);
                        card.error = None;
                    }
                    Err(error) if matches!(card.settings, Loadable::Ready(_)) => {
                        card.error = Some(error);
                    }
                    Err(error) => card.settings = Loadable::Error(error),
                }
                cx.notify();
            });
        }));
        cx.notify();
    }

    /// Opens the guide to "Paste from Other Apps" on this Mac: one read that raises the prompt
    /// when the app was never asked (so it is listed), then System Settings at the list. Reads
    /// the state again a moment later.
    #[cfg(target_os = "macos")]
    fn open_guide(&mut self, cx: &mut Context<Self>) {
        use onicode_grants::paste;
        if !paste::behavior().listed() {
            // The read blocks while the prompt is up: off the main thread.
            std::thread::spawn(paste::ask_once);
        }
        let _opened = paste::open_settings(objc2::MainThreadMarker::new());
        cx.spawn(async move |this, cx| {
            cx.background_executor()
                .timer(std::time::Duration::from_secs(5))
                .await;
            let _gone = this.update(cx, |card, cx| card.call(None, cx));
        })
        .detach();
    }

    #[cfg(not(target_os = "macos"))]
    fn open_guide(&mut self, _cx: &mut Context<Self>) {}
}

/// What the paste permission row says.
fn paste_line(paste: Option<PasteAccess>) -> &'static str {
    match paste {
        None => "Loading…",
        Some(PasteAccess::Ungated) => "Not needed on this device.",
        Some(PasteAccess::Allowed) => "Allowed: copies here reach your other devices at once.",
        Some(access) => access.why().unwrap_or_default(),
    }
}

impl Render for ClipboardCard {
    fn render(&mut self, _: &mut gpui::Window, cx: &mut Context<Self>) -> impl IntoElement {
        crate::toast::take_error(&mut self.error, cx);
        let theme = Theme::of(cx).for_settings_surface();
        let ready = self.settings.ready().copied();
        let enabled = ready.is_none_or(|s| s.enabled);
        let auto_generated = ready.is_some_and(|s| s.auto_generated);
        let paste = ready.map(|s| s.paste);
        let needs_guide = cfg!(target_os = "macos")
            && paste.is_some_and(|p| !matches!(p, PasteAccess::Allowed | PasteAccess::Ungated));
        let toggle = |key: &'static str, id: &'static str, label: &'static str, on: bool| {
            widgets::toggle_switch(&theme, on, key)
                .id(id)
                .cursor_pointer()
                .tab_index(0)
                .role(gpui::Role::Switch)
                .aria_label(label)
                .aria_toggled(if on {
                    gpui::Toggled::True
                } else {
                    gpui::Toggled::False
                })
                .focus_visible(|s| s.border_2().border_color(theme.accent).opacity(1.0))
        };
        let row = |first: bool, title: &'static str, line: &'static str| {
            widgets::card_row(&theme, first).child(
                div()
                    .flex_1()
                    .min_w(px(160.0))
                    .flex()
                    .flex_col()
                    .child(widgets::row_title(&theme, title))
                    .child(widgets::meta_line(
                        &theme,
                        vec![div().child(line).into_any_element()],
                    )),
            )
        };
        let card = widgets::section_card(&theme)
            .mt_0()
            .child(
                row(
                    true,
                    "Follow the clipboard",
                    "Copy on one device, paste on another.",
                )
                .child(
                    toggle(
                        "clipboard-sync",
                        "clipboard-sync-toggle",
                        "Follow the clipboard",
                        enabled,
                    )
                    .on_click(cx.listener(move |card, _, _, cx| {
                        if card.settings.ready().is_some() {
                            card.call(Some(Change::Enabled(!enabled)), cx);
                        }
                    })),
                )
                .search_anchor(SettingId::ClipboardSync),
            )
            .child(
                row(
                    false,
                    "Include copies apps make",
                    "Copies an app marks as made on its own, not by you.",
                )
                .child(
                    toggle(
                        "clipboard-auto-generated",
                        "clipboard-auto-generated-toggle",
                        "Include copies apps make",
                        auto_generated,
                    )
                    .on_click(cx.listener(move |card, _, _, cx| {
                        if card.settings.ready().is_some() {
                            card.call(Some(Change::AutoGenerated(!auto_generated)), cx);
                        }
                    })),
                )
                .search_anchor(SettingId::ClipboardAutoGenerated),
            )
            .child(
                row(false, "Paste from Other Apps", paste_line(paste))
                    .when(needs_guide, |row| {
                        row.child(
                            widgets::text_action(&theme, widgets::ActionTone::Filled, "Open guide")
                                .id("clipboard-paste-guide")
                                .tab_index(0)
                                .role(gpui::Role::Button)
                                .aria_label("Allow Paste from Other Apps")
                                .focus_visible(|s| s.border_2().border_color(theme.accent))
                                .on_click(cx.listener(|card, _, _, cx| card.open_guide(cx))),
                        )
                    })
                    .search_anchor(SettingId::ClipboardPaste),
            );
        widgets::section(&theme, "Clipboard", card)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_paste_state_has_words() {
        for access in [
            PasteAccess::Ungated,
            PasteAccess::NotAsked,
            PasteAccess::Ask,
            PasteAccess::Allowed,
            PasteAccess::Denied,
        ] {
            assert!(!paste_line(Some(access)).is_empty(), "{access:?}");
        }
        assert!(paste_line(Some(PasteAccess::Denied)).contains("stay here"));
    }
}
