//! The clipboard that follows the owner between peers (`docs/onicode/decisions/one-machine.md`):
//! the payloads of `WatchClipboard`, `ClipboardOffer`, `ClipboardFetch` and
//! `ClipboardSettings`. The bytes of a large item come on a `clip/<originSeq>/<type>` file
//! stream, not in these.

use serde::{Deserialize, Serialize};

/// Items up to this many bytes ride inside the offer.
pub const INLINE_MAX: u64 = 16 << 10;

/// One pasteboard type of an item.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClipboardType {
    /// Its uniform type identifier (`public.utf8-plain-text`).
    pub uti: String,
    /// Its bytes; 0 when the origin may not read them unasked (macOS's "Paste from Other
    /// Apps"), and they come only on paste.
    pub size: u64,
    /// The bytes themselves, base64, when `size <= INLINE_MAX`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub inline: Option<String>,
    /// For a `public.file-url`, the size of the regular file it names; `None` for a folder or
    /// when unknown. A receiver prefetches small files before the paste.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub file_size: Option<u64>,
}

/// One pasteboard item: the same content in each of its types.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClipboardItem {
    /// Its types, the richest first.
    pub types: Vec<ClipboardType>,
}

/// A copy announced to the owner's other engines and clients, an item of `WatchClipboard`.
/// The newest `(at, originDevice)` wins.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClipboardOffer {
    /// The device it was copied on.
    pub origin_device: String,
    /// That device's count of offers, which names this one in a fetch.
    pub origin_seq: u64,
    /// When it was copied, epoch milliseconds.
    pub at: i64,
    /// What was copied.
    pub items: Vec<ClipboardItem>,
    /// Marked concealed at the origin. Such an offer is never sent; the flag is kept for a
    /// receiver's own checks.
    #[serde(default)]
    pub concealed: bool,
}

/// `ClipboardFetch`: one type of one offer, from its origin.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClipboardFetchRequest {
    /// The offer.
    pub origin_seq: u64,
    /// The item, by its place in the offer: a copy of several pictures has one type per item.
    #[serde(default)]
    pub item: usize,
    /// The type's UTI.
    #[serde(rename = "type")]
    pub uti: String,
}

/// `ClipboardSettings`: each engine's own. A call with no fields reads them; a field sets it.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClipboardSettingsRequest {
    /// Follow the clipboard at all.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub enabled: Option<bool>,
    /// Send items marked `org.nspasteboard.AutoGeneratedType` too.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub auto_generated: Option<bool>,
}

/// `ClipboardSettings`' reply.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClipboardSettings {
    /// Follow the clipboard at all.
    pub enabled: bool,
    /// Send auto-generated items too.
    pub auto_generated: bool,
}

impl Default for ClipboardSettings {
    fn default() -> Self {
        Self {
            enabled: true,
            auto_generated: false,
        }
    }
}
