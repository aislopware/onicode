/** The one built-in look. The CLI and the theme tool switch back to it by this id. */
export const BUILT_IN_THEME_ID = "onicode";

/** Appearance keywords, so a custom theme cannot capture a stored preference. */
export const RESERVED_THEME_IDS: ReadonlySet<string> = new Set(["system", "light", "dark"]);

/** The built-in id names the standard look, so no published file can take it. */
export const UNPUBLISHABLE_THEME_IDS: ReadonlySet<string> = new Set([
  ...RESERVED_THEME_IDS,
  BUILT_IN_THEME_ID,
]);

