export type ClientGuardedRpcTag = keyof typeof CLIENT_GUARDED_RPC_SCOPES;

const decodePrepareThread = Schema.decodeUnknownSync(GitPreparePullRequestThreadInput);
const decodeStackedAction = Schema.decodeUnknownSync(GitRunStackedActionInput);
const isMcpSignInAction = Schema.is(
  Schema.Struct({ action: Schema.Literals(["authenticate", "clear-auth"]) }),
);
const decodeLinkPairing = Schema.decodeUnknownSync(PeerLinkLinkPairingInput);

export function clientRpcRequiredScopes(
  method: string,
  input: unknown,
): readonly AuthEnvironmentScope[] {
  if (method === WS_METHODS.gitPreparePullRequestThread && input !== undefined) {
    const payload = decodePrepareThread(input);
    if (payload.mode === "worktree" && payload.threadId !== undefined)
      return [AuthSourceControlWriteScope, AuthOrchestrationOperateScope];
  }
  if (method === WS_METHODS.gitRunStackedAction && input !== undefined) {
    const payload = decodeStackedAction(input);
    if (
      payload.threadId !== undefined &&
      (payload.action === "create_pr" || payload.action === "commit_push_pr")
    )
      return [AuthSourceControlWriteScope, AuthOrchestrationReadScope];
  }
  if (method === WS_METHODS.serverUpdateSettings && input !== undefined) {
    const scopes = requiredScopesForServerSettingsUpdate(
      input as Parameters<typeof requiredScopesForServerSettingsUpdate>[0],
    );
    // Only script writes wait for the grants here. Other settings writes go out before grants
    // load (shared settings sync relies on it), and the server checks them with the same rule.
    return scopes.includes(AuthOrchestrationOperateScope) ? scopes : [];
  }
  // Signing in or out of an MCP server changes a stored credential, as provider.mcpSignIn does.
  if (method === WS_METHODS.providerSessionMcpServerAction && isMcpSignInAction(input))
    return [AuthOrchestrationOperateScope, AuthProvidersManageScope];
  // Handing out access takes holding it: the caller gets back a credential it can spend itself.
  if (method === WS_METHODS.peerLinksPairLink && input !== undefined) {
    const held = mcpClientScopes(decodeLinkPairing(input).access);
    return [AuthAccessWriteScope, ...held];
  }
  // Checking a secret source resolves a caller-named reference and applies it to providers.
  if (method === WS_METHODS.serverCheckSecretSource) {
    return [AuthSettingsWriteScope, AuthProvidersManageScope];
  }
  return Object.hasOwn(CLIENT_GUARDED_RPC_SCOPES, method)
    ? [CLIENT_GUARDED_RPC_SCOPES[method as ClientGuardedRpcTag]]
    : [];
}
